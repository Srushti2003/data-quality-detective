def get_rule_condition(df, rule_name):
    """Return the condition generated by a named rule."""
    rules = get_advanced_rules(df)

    matching_rule = next(
        rule for rule in rules
        if rule["name"] == rule_name
    )

    return matching_rule["condition"]


def test_zero_trip_distance_detected(valid_dataframe):
    valid_dataframe.loc[0, "trip_distance"] = 0

    result = get_rule_condition(
        valid_dataframe, "zero_trip_distance"
    )

    assert result.iloc[0] == True


